function recipe(data: CompactRecipe): RealRecipeSeed {
  const publishedAt = PUBLISHED_AT_BY_SLUG[data.slug];
  if (!publishedAt) {
    throw new Error(`Missing publication date for recipe "${data.slug}"`);
  }

  return {
    ...data,
    instructions: data.steps.map((step) => step.description).join(' '),
    publishedAt,
  };
}

const ingredient = (
  name: string,
  quantity: number,
  unit: string,
  notes?: string,
): SeedIngredient => ({
  name,
  quantity,
  unit,
  ...(notes ? { notes } : {}),
});

const step = (title: string, description: string, timerMinutes?: number): SeedStep => ({
  title,
  description,
  ...(timerMinutes === undefined ? {} : { timerMinutes }),
});

